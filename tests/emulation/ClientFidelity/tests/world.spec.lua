-- Loot slots, bags, guild roster, item info and ColorSelect (client loot
-- frame, Script_GetContainer*, Script_GetGuildRosterInfo, Script_GetItemInfo,
-- CSimpleColorSelect).
test("a master-looted item clears its slot with LOOT_SLOT_CLEARED", function()
    local cleared = {}
    local f = CreateFrame("Frame")
    f:RegisterEvent("LOOT_SLOT_CLEARED")
    f:SetScript("OnEvent", function(_, _, slot) table.insert(cleared, slot) end)
    forge.masterLoot({ "Tester", "Bot" })
    forge.openLoot({ "|cffa335ee|Hitem:20513:0:0:0:0:0:0:0:80|h[Abyssal Crest]|h|r" })
    GiveMasterLoot(1, 2)
    expect(#cleared).toBe(0)
    forge.advance(0.05)
    expect(cleared).toEqual({ 1 })
    expect(GetLootSlotLink(1)).toBeNil()
    forge.closeLoot()
end)

test("bags: the backpack has 16 slots, empty slots have no link", function()
    expect(GetContainerNumSlots(0)).toBe(16)
    expect(GetContainerNumSlots(-2)).toBe(32)
    expect(GetContainerNumSlots(1)).toBe(0)
    forge.bag(1, 10, { [3] = "|cff1eff00|Hitem:17922:0:0:0:0:0:0:0:60|h[Lionfur Armor]|h|r" })
    expect(GetContainerNumSlots(1)).toBe(10)
    expect(GetContainerItemLink(1, 3)).toContain("Lionfur Armor")
    expect(GetContainerItemLink(1, 4)).toBeNil()
    expect(NUM_BAG_SLOTS).toBe(4)
    expect(pcall(GetContainerNumSlots)).toBeFalsy()
end)

test("guild roster: online members by default, 11 values per member", function()
    expect(IsInGuild()).toBeNil()
    expect(GetNumGuildMembers()).toBe(0)
    forge.guild({ name = "Forge", members = { { name = "Ann", rankName = "Officer", rankIndex = 1 },
                                              { name = "Bob", online = false } } })
    expect(IsInGuild()).toBe(1)
    expect(GetNumGuildMembers()).toBe(1)
    expect(GetNumGuildMembers(true)).toBe(2)
    local name, rank, rankIndex, _, _, _, _, _, online, status, token = GetGuildRosterInfo(1)
    expect(name).toBe("Ann")
    expect(rank).toBe("Officer")
    expect(rankIndex).toBe(1)
    expect(online).toBe(1)
    expect(status).toBe("")
    expect(token).toBe("WARRIOR")
    expect(select("#", GetGuildRosterInfo(9))).toBe(11)
    local updates = 0
    local f = CreateFrame("Frame")
    f:RegisterEvent("GUILD_ROSTER_UPDATE")
    f:SetScript("OnEvent", function() updates = updates + 1 end)
    GuildRoster()
    expect(updates).toBe(0)
    forge.advance(0.05)
    expect(updates).toBe(1)
end)

test("GetItemInfo needs an id, name or link", function()
    local ok, err = pcall(GetItemInfo, nil)
    expect(ok).toBeFalsy()
    expect(err).toContain("Usage: GetItemInfo")
    expect(GetItemInfo(424242)).toBeNil()     -- not in the item cache
end)

test("ColorSelect:SetColorRGB runs OnColorSelect at once", function()
    local seen = 0
    ColorPickerFrame:SetScript("OnColorSelect", function() seen = seen + 1 end)
    ColorPickerFrame:SetColorRGB(1, 0.5, 0)
    expect(seen).toBe(1)
    local r, g, b = ColorPickerFrame:GetColorRGB()
    expect(r).toBe(1)
    expect(g).toBe(0.5)
    expect(b).toBe(0)
    expect(ColorPickerFrame:IsShown()).toBe(false)
end)
