-- FontString/Button/EditBox text (client CSimpleFontString::SetText,
-- LanguageProcess, CSimpleButton::SetText, CSimpleEditBox Script_SetText).
local function label()
    return UIParent:CreateFontString(nil, "OVERLAY", "GameFontNormal")
end

test("SetText on a font string without a font is an error", function()
    local bare = UIParent:CreateFontString("ClientFidelityBare", "OVERLAY")
    local ok, err = pcall(bare.SetText, bare, "x")
    expect(ok).toBeFalsy()
    expect(err).toContain("ClientFidelityBare:SetText(): Font not set")
    bare:SetFontObject(GameFontNormal)
    bare:SetText("x")
    expect(bare:GetText()).toBe("x")
end)

test("empty text reads back as nil", function()
    local fs = label()
    fs:SetText("")
    expect(fs:GetText()).toBeNil()
    fs:SetText("a")
    fs:SetText(nil)
    expect(fs:GetText()).toBeNil()
end)

test("numbers become text, other types clear it", function()
    local fs = label()
    fs:SetText(5)
    expect(fs:GetText()).toBe("5")
    fs:SetText(1.5)
    expect(fs:GetText()).toBe("1.5")
    fs:SetText(true)
    expect(fs:GetText()).toBeNil()
    fs:SetText({})
    expect(fs:GetText()).toBeNil()
end)

test("colour escapes are kept, |4 plural forms are resolved", function()
    local fs = label()
    fs:SetText("|cffff0000red|r")
    expect(fs:GetText()).toBe("|cffff0000red|r")
    fs:SetText("3 |4item:items;")
    expect(fs:GetText()).toBe("3 items")
    fs:SetFormattedText("%d |4Stunde:Stunden; left", 1)
    expect(fs:GetText()).toBe("1 Stunde left")
end)

test("a plain button has no font string until it gets text", function()
    local b = CreateFrame("Button", nil, UIParent)
    expect(b:GetFontString()).toBeNil()
    b:SetText("")
    expect(b:GetFontString()).toBeNil()
    expect(b:GetText()).toBeNil()
    b:SetText("Go")
    expect(b:GetText()).toBe("Go")
    expect(b:GetFontString()).toBeTruthy()
    b:SetText("")
    expect(b:GetText()).toBeNil()
end)

test("EditBox:SetText(nil) is an error, numbers are text", function()
    local box = CreateFrame("EditBox", "ClientFidelityBox", UIParent)
    local ok, err = pcall(box.SetText, box, nil)
    expect(ok).toBeFalsy()
    expect(err).toContain('ClientFidelityBox:SetText("text")')
    box:SetText(42)
    expect(box:GetText()).toBe("42")
end)

-- CSimpleFontString starts with style flags 0x212 (CENTER | MIDDLE);
-- Script_GetJustifyH/V return JustifyToString of the masked flags and
-- Script_SetJustifyH/V match names case-insensitively (StringToJustify).
test("justification reads back, defaults to CENTER and MIDDLE", function()
    local fs = label()
    expect(fs:GetJustifyH()).toBe("CENTER")
    expect(fs:GetJustifyV()).toBe("MIDDLE")
    fs:SetJustifyH("left")
    fs:SetJustifyV("TOP")
    expect(fs:GetJustifyH()).toBe("LEFT")
    expect(fs:GetJustifyV()).toBe("TOP")
    local named = UIParent:CreateFontString("ClientFidelityJustify", "OVERLAY", "GameFontNormal")
    local ok, err = pcall(named.SetJustifyH, named, "SIDEWAYS")
    expect(ok).toBeFalsy()
    expect(err).toContain('Usage: ClientFidelityJustify:SetJustifyH("justify")')
    expect(named:GetJustifyH()).toBe("CENTER")
end)
