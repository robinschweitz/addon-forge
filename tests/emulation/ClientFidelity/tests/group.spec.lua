-- Groups (client Script_GetRaidRosterInfo, Script_IsRaidLeader,
-- Script_IsRaidOfficer, Script_ConvertToRaid, Script_InviteUnit).
test("GetRaidRosterInfo outside the raid gives the client's defaults", function()
    local name, rank, subgroup, level = GetRaidRosterInfo(1)
    expect(name).toBeNil()
    expect(rank).toBe(0)
    expect(subgroup).toBe(1)
    expect(level).toBe(1)
    expect(select("#", GetRaidRosterInfo(1))).toBe(14)
end)

test("an offline raid member's zone is the Offline text", function()
    forge.raid({ { name = "Tester", rank = 2 }, { name = "Gone", online = false } })
    local _, _, _, _, _, _, zone, online = GetRaidRosterInfo(2)
    expect(zone).toBe("Offline")
    expect(online).toBeNil()
    forge.raid({})
end)

test("IsRaidLeader is true for a party leader; IsRaidOfficer needs raid rank", function()
    forge.party({ "Bot" })
    forge.leader(true)
    expect(IsRaidLeader()).toBe(1)
    expect(IsRaidOfficer()).toBeNil()
    forge.leader(false)
    forge.raid({ { name = "Bot", rank = 2 }, { name = "Tester", rank = 1 } })
    expect(IsRaidLeader()).toBeNil()
    expect(IsRaidOfficer()).toBe(1)
    forge.raid({})
    forge.party({})
end)

test("ConvertToRaid needs a party, the lead and level 10", function()
    ConvertToRaid()
    forge.advance(0.05)
    expect(GetNumRaidMembers()).toBe(0)
    forge.party({ "Bot" })
    forge.leader(true)
    forge.unit("player", { level = 9 })
    ConvertToRaid()
    forge.advance(0.05)
    expect(GetNumRaidMembers()).toBe(0)
    forge.unit("player", { level = 80 })
    ConvertToRaid()
    expect(GetNumRaidMembers()).toBe(0)     -- the server answers next frame
    forge.advance(0.05)
    expect(GetNumRaidMembers()).toBe(2)
    expect(IsRaidOfficer()).toBe(1)
end)

test("InviteUnit sends names up to 48 bytes", function()
    InviteUnit("Bot")
    InviteUnit(nil)
    expect(forge.invites()).toEqual({ "Bot" })
    local ok, err = pcall(InviteUnit, string.rep("x", 49))
    expect(ok).toBeFalsy()
    expect(err).toContain("Name too long")
end)
