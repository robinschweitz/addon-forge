import pytest
from addon_forge.reports import parse_report, ReportParseError


def test_parse_savedvariables():
    lua = '''-- generated by WoW
    ForgeTestReport = {
      ["runId"] = "a1b2",
      ["completed"] = true,
      ["errors"] = { },
      ["tests"] = {
        { ["name"] = "loaded", ["status"] = "passed" },
        { ["name"] = "size", ["status"] = "failed", ["error"] = "expected 20, got 0" },
      },
    }
    '''
    result = parse_report(lua)
    assert result["runId"] == "a1b2"
    assert result["completed"] is True
    assert result["tests"][1]["status"] == "failed"
    assert result["errors"] == {}


def test_no_arbitrary_lua_execution():
    with pytest.raises(ReportParseError):
        parse_report('ForgeTestReport = os.execute("bad")')
    with pytest.raises(ReportParseError):
        parse_report('ForgeTestReport = {} print("hello")')


def test_limits_and_string_unescape():
    result = parse_report('ForgeTestReport = { text = "hello\\nthere", num = -17, [2] = "x" }')
    assert result["text"] == "hello\nthere"
    assert result["num"] == -17
    assert result[2] == "x"


def test_encoded_lua_string():
    assert parse_report('ForgeTestReport = { text = "a\\065b" }')["text"] == "aAb"
