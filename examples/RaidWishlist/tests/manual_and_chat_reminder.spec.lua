-- Wishlist entries can be maintained without the website. Chat reminders are
-- deliberately strict: an item link and one configured keyword are both needed.
local CREST = "|cffa335ee|Hitem:20513:0:0:0:0:0:0:0:80|h[Abyssal Crest]|h|r"

before_load(function()
    forge.item(20513, { name = "Abyssal Crest", link = CREST, quality = 4 })
    forge.item(20514, { name = "Second Item", quality = 4 })
    forge.item(20515, { name = "Third Item", quality = 4 })
end)

local function db() return forge.saved("RaidWishlistDB") end

test("manual entries can be created, changed and removed in the addon", function()
    forge.slash("/wish")
    forge.click("RaidWishlistEditOpen")
    expect("RaidWishlistEditorPanel").toBeShown()
    expect(forge.layoutIssues("RaidWishlistEditorPanel")).toEqual({})
    forge.sketch("manual-editor", RaidWishlistEditorPanel)
    forge.type("RaidWishlistEditorItem", "20513")
    forge.type("RaidWishlistEditorNote", "Manual BiS")
    forge.click("RaidWishlistEditorSave")
    expect(db().chars.Tester.items[1].itemID).toBe(20513)
    expect(db().chars.Tester.items[1].spec).toBe("ms")
    expect(db().chars.Tester.items[1].note).toBe("Manual BiS")
    expect(forge.findText("1. " .. CREST)).toBeTruthy()

    forge.click("RaidWishlistWish1")
    forge.type("RaidWishlistEditorNote", "Changed")
    forge.click("RaidWishlistEditorOS")
    forge.click("RaidWishlistEditorSave")
    expect(db().chars.Tester.items[1].spec).toBe("os")
    expect(db().chars.Tester.items[1].note).toBe("Changed")

    forge.click("RaidWishlistWish1")
    forge.click("RaidWishlistEditorDelete")
    expect(#db().chars.Tester.items).toBe(0)
    expect(forge.layoutIssues("RaidWishlistFrame")).toEqual({})
end)

test("chat reminders require a matching keyword and follow sender settings", function()
    forge.slash("/wish edit")
    forge.type("RaidWishlistEditorItem", "20513")
    forge.click("RaidWishlistEditorSave")
    forge.raid({ "Lead", "Alice" })
    forge.stub("GetLootMethod", function() return "master", nil, 1 end)

    forge.chatEvent("CHAT_MSG_RAID", "roll " .. CREST, "Alice")
    expect("RaidWishlistPrompt").toBeHidden()
    forge.chatEvent("CHAT_MSG_RAID", "Abyssal Crest " .. CREST, "Lead")
    expect("RaidWishlistPrompt").toBeHidden()
    forge.chatEvent("CHAT_MSG_RAID", "roll " .. CREST, "Lead")
    expect("RaidWishlistPrompt").toBeShown()
    forge.click("RaidWishlistSkip")

    forge.click("RaidWishlistSettingsOpen")
    expect(forge.layoutIssues("RaidWishlistSettingsPanel")).toEqual({})
    forge.sketch("chat-reminder", RaidWishlistSettingsPanel)
    forge.frame("RaidWishlistReminderKeywords"):SetText("ready")
    forge.click("RaidWishlistReminderAll")
    forge.click("RaidWishlistReminderSave")
    expect(db().chars.Tester.reminderKeywords).toBe("ready")
    expect("RaidWishlistPrompt").toBeHidden()
    forge.chatEvent("CHAT_MSG_RAID", "roll " .. CREST, "Alice")
    expect("RaidWishlistPrompt").toBeHidden()
    forge.chatEvent("CHAT_MSG_RAID", "ready " .. CREST, "Alice")
    expect("RaidWishlistPrompt").toBeShown()
    expect(forge.layoutIssues("RaidWishlistPrompt")).toEqual({})
end)

test("changing an entry's item ID replaces it; an ID already listed is refused", function()
    forge.slash("/wish edit")
    forge.type("RaidWishlistEditorItem", "20514")
    forge.click("RaidWishlistEditorSave")
    expect(#db().chars.Tester.items).toBe(2)

    forge.click("RaidWishlistWish1")
    forge.frame("RaidWishlistEditorItem"):SetText("20515")
    forge.click("RaidWishlistEditorSave")
    expect(#db().chars.Tester.items).toBe(2)
    expect(db().chars.Tester.items[1].itemID).toBe(20515)
    expect(db().chars.Tester.items[2].itemID).toBe(20514)

    forge.click("RaidWishlistWish1")
    forge.frame("RaidWishlistEditorItem"):SetText("20514")
    forge.click("RaidWishlistEditorSave")
    expect("RaidWishlistEditorPanel").toBeShown()
    expect(forge.findText("That item is already on your wishlist.")).toBeTruthy()
    expect(#db().chars.Tester.items).toBe(2)
    expect(db().chars.Tester.items[1].itemID).toBe(20515)
    expect(forge.layoutIssues("RaidWishlistEditorPanel")).toEqual({})
end)
