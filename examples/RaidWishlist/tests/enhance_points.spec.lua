local CREST = "|cffa335ee|Hitem:20513:0:0:0:0:0:0:0:80|h[Abyssal Crest]|h|r"

before_load(function()
    forge.item(20513, { name = "Abyssal Crest", link = CREST, quality = 4 })
end)

local function db() return forge.saved("RaidWishlistDB") end
local rolls = {}

test("current Enhance points are saved per character and set the enhanced roll range", function()
    forge.slash("/wish")
    forge.click("RaidWishlistSettingsOpen")
    expect("RaidWishlistSettingsPanel").toBeShown()
    forge.frame("RaidWishlistEditorPoints"):SetText("37")
    forge.click("RaidWishlistEditorPointsSave")
    expect(db().chars.Tester.balance).toBe(37)
    expect(db().chars.Tester.spent).toEqual({})

    forge.slash("/wish edit")
    forge.frame("RaidWishlistEditorItem"):SetText("20513")
    forge.click("RaidWishlistEditorEnhanced")
    forge.click("RaidWishlistEditorSave")
    forge.raid({ "Lead", "Alice" })
    forge.stub("RandomRoll", function(low, high) table.insert(rolls, { low, high }) end)
    forge.fire("CHAT_MSG_ADDON", "FLLedger", "S;Lead-1;Lead;Lead-1-1;20513;30;1;", "RAID", "Lead")
    forge.click("RaidWishlistRoll")
    expect(rolls).toEqual({ { 38, 137 } })

    forge.reload()
    forge.slash("/wish edit")
    forge.click("RaidWishlistSettingsFromEditor")
    expect(forge.frame("RaidWishlistEditorPoints"):GetText()).toBe("37")
end)

test("invalid Enhance points leave the current balance unchanged", function()
    forge.slash("/wish edit")
    forge.click("RaidWishlistSettingsFromEditor")
    forge.frame("RaidWishlistEditorPoints"):SetText("37")
    forge.click("RaidWishlistEditorPointsSave")
    forge.frame("RaidWishlistEditorPoints"):SetText("-1")
    forge.click("RaidWishlistEditorPointsSave")
    expect(db().chars.Tester.balance).toBe(37)
    expect(forge.findText("Enter a whole number from 0 to 999999.")).toBeTruthy()
end)

test("the settings page shows the real balance, so saving it unchanged keeps 70", function()
    forge.slash("/wish import")
    forge.type("RaidWishlistImportText", "WL2;Tester;1792130000;70\n20513;m;1;1;")
    forge.click("RaidWishlistImportButton")
    expect(db().chars.Tester.balance).toBe(70)
    forge.slash("/wish edit")
    forge.click("RaidWishlistSettingsFromEditor")
    expect(forge.frame("RaidWishlistEditorPoints"):GetText()).toBe("70")
    forge.click("RaidWishlistEditorPointsSave")
    expect(db().chars.Tester.balance).toBe(70)
    forge.click("RaidWishlistReminderSave")
    expect(db().chars.Tester.balance).toBe(70)
end)

test("SAVE SETTINGS saves typed points; CANCEL discards the sender mode", function()
    forge.click("RaidWishlistSettingsOpen")
    forge.frame("RaidWishlistEditorPoints"):SetText("12")
    forge.click("RaidWishlistReminderSave")
    expect(db().chars.Tester.balance).toBe(12)

    forge.click("RaidWishlistSettingsOpen")
    forge.click("RaidWishlistReminderAll")
    forge.click("RaidWishlistReminderCancel")
    expect(db().chars.Tester.reminderAll).toBe(nil)
    forge.click("RaidWishlistSettingsOpen")
    forge.click("RaidWishlistReminderAll")
    forge.click("RaidWishlistReminderSave")
    expect(db().chars.Tester.reminderAll).toBe(true)
end)

test("an invalid value on the settings page saves nothing", function()
    forge.click("RaidWishlistSettingsOpen")
    forge.frame("RaidWishlistEditorPoints"):SetText("-5")
    forge.frame("RaidWishlistReminderKeywords"):SetText("ready")
    forge.click("RaidWishlistReminderSave")
    expect("RaidWishlistSettingsPanel").toBeShown()
    expect(forge.findText("Enter a whole number from 0 to 999999.")).toBeTruthy()
    expect(db().chars.Tester.balance).toBe(12)
    expect(db().chars.Tester.reminderKeywords).toBe("roll,würfel")
end)
