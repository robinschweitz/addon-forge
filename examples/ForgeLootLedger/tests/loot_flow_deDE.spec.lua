-- German client: RANDOM_ROLL_RESULT uses positional specifiers, and every
-- system chat line (e.g. idle-logout notices) reaches the roll parser.
before_load(function()
    forge.locale("deDE", { RANDOM_ROLL_RESULT = "%1$s würfelt. Ergebnis: %2$d (%3$d-%4$d)" })
    forge.item(20513, { name = "Abyssisches Wappen", link = "|cffa335ee|Hitem:20513:0:0:0:0:0:0:0:80|h[Abyssisches Wappen]|h|r", quality = 4 })
end)

test("unrelated system messages do not raise Lua errors", function()
    forge.fire("CHAT_MSG_SYSTEM", "Ihr wart für einige Zeit inaktiv und werdet jetzt vom Spiel abgemeldet.")
    expect(#forge.errors()).toBe(0)
end)

test("German /rnd results are recorded and the highest wins", function()
    forge.openLoot({ { id = 20513 } })
    forge.slash("/forgeloot start")
    forge.roll("Anna", 12)
    forge.roll("Bernd", 88)
    forge.advance(31, 0.25)
    expect(forge.chat()).toContain("gewonnen von Bernd (88) - Main-Spec, bisher 0 Items.")
end)

test("the ledger window is German and the longer texts still fit", function()
    if not ForgeLootLedgerFrame:IsShown() then forge.slash("/forgeloot") end   -- loot opened it already
    expect("ForgeLootLedgerFrame").toBeShown()
    expect(forge.findText("PLÜNDERMEISTER-BUCH")).toBeTruthy()
    expect(forge.findText("BEUTE  /  WÜRFE  /  VERGABEN")).toBeTruthy()
    expect(forge.findText("PARKEN")).toBeTruthy()
    expect(forge.findText("LEEREN")).toBeTruthy()
    expect(forge.layoutIssues("ForgeLootLedgerFrame")).toEqual({})
    forge.slash("/forgeloot export")
    expect(forge.findText("EXPORT FÜR DIE WEBSEITE  (RS2 LOOT)")).toBeTruthy()
    expect(forge.layoutIssues("ForgeLootLedgerFrame")).toEqual({})
end)

test("help, usage and a tie are German too", function()
    forge.slash("/forgeloot help")
    expect(forge.chat()).toContain("ForgeLootLedger: /forgeloot start - 30 s /rnd-Wurf für den gewählten Gegenstand starten")
    forge.slash("/forgeloot set")
    expect(forge.chat()).toContain("ForgeLootLedger: Aufruf: /forgeloot set <#> [Name]")
    forge.openLoot({ { id = 20513 } })
    forge.slash("/forgeloot start")
    forge.roll("Anna", 50)
    forge.roll("Bernd", 50)
    forge.advance(31, 0.25)
    expect(forge.chat()).toContain("Gleichstand zwischen Anna und Bernd (50)! Anna, Bernd: nochmal /rnd, 15 Sekunden.")
end)

test("the raid setup is German and fits", function()
    forge.click("ForgeLootLedgerRaidButton")
